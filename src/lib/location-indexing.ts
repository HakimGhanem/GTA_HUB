import { REGIONAL_LOCATION_SLUGS } from "@/data/location-seo-types";
import type { Location } from "@/data/locations";
import { getLocalityPages, localitySlug } from "@/lib/real-world-matches";

const REGIONAL_HUBS = new Set<string>(REGIONAL_LOCATION_SLUGS);

export function isRegionalHubSlug(slug: string): boolean {
  return REGIONAL_HUBS.has(slug);
}

/** Matches slugs like gtadb-l1-vice-beach-1409-2803 */
export const GTADB_SLUG_PATTERN = /gtadb-l\d+/;

type LocationIndexingFields = Pick<
  Location,
  "slug" | "name" | "description"
> & {
  source?: string;
};

export function isGtadbAutoGeneratedSlug(slug: string): boolean {
  return slug.includes("gtadb") || GTADB_SLUG_PATTERN.test(slug);
}

/** Thin editorial stubs — keep on site for map pins, exclude from SEO/AdSense crawl surface */
const THIN_STUB_SLUGS = new Set([
  "hidden-package-01",
  "grassroots-weapons",
  "everglades-lookout",
]);

export function isThinStubLocation(
  location: LocationIndexingFields,
): boolean {
  return THIN_STUB_SLUGS.has(location.slug);
}

export function isGtadbAutoGeneratedLocation(
  location: LocationIndexingFields,
): boolean {
  if (location.source === "gtadb") return true;
  if (isGtadbAutoGeneratedSlug(location.slug)) return true;
  if (location.description.includes("community-mapped location")) return true;
  if (location.name.includes("community-mapped location")) return true;
  return false;
}

/** Sample collectible pins — map only, not individual SEO pages */
const COLLECTIBLE_SEED_PREFIXES = [
  "hidden-package-",
  "stunt-jump-",
  "street-art-",
  "wildlife-",
] as const;

export function isCollectibleSeedLocation(
  location: LocationIndexingFields & { category?: string },
): boolean {
  if (location.category === "collectible") return true;
  return COLLECTIBLE_SEED_PREFIXES.some((p) => location.slug.startsWith(p));
}

export function shouldNoindexLocation(
  location: LocationIndexingFields & { category?: string },
): boolean {
  if (isRegionalHubSlug(location.slug)) return false;
  return true;
}

/** Hubs only — sitemap + Google index. */
export function getIndexableLocations(locations: Location[]): Location[] {
  return locations.filter((loc) => isRegionalHubSlug(loc.slug));
}

/** Hubs + editorial POIs for on-site browse. Map pins stay via getAllLocations. */
export function getBrowsableLocations(locations: Location[]): Location[] {
  return locations.filter(
    (loc) =>
      !isGtadbAutoGeneratedLocation(loc) &&
      !isThinStubLocation(loc) &&
      !isCollectibleSeedLocation(loc),
  );
}

export function hasOwnLocationPage(
  location: LocationIndexingFields & { category?: string },
): boolean {
  if (isRegionalHubSlug(location.slug)) return true;
  return (
    !isGtadbAutoGeneratedLocation(location) &&
    !isThinStubLocation(location) &&
    !isCollectibleSeedLocation(location)
  );
}

const COLLECTIBLE_PREFIX_TYPE: Record<string, string> = {
  "hidden-package-": "hidden-packages",
  "stunt-jump-": "stunt-jumps",
  "street-art-": "street-art",
  "wildlife-": "wildlife",
};

/**
 * Region names in the GTADB import are postal-style (`Stockyard, Vice City`,
 * `Catalan Key`), so they are matched by the district they belong to rather
 * than compared to hub slugs directly.
 */
const REGION_HUB_PATTERNS: Array<[RegExp, string]> = [
  [/vice beach|ocean drive/i, "ocean-drive"],
  [/vice city|vice-dale|tequesta|la perle|crosstown|rockridge|stockyard/i, "vice-city"],
  [/key|leonida keys|waning sands/i, "leonida-keys"],
  [/port gellhorn|hamlet|kelly county|leonard county/i, "port-gellhorn"],
  [/ambrosia|watson bay|mariana county/i, "ambrosia-island"],
  [/grassrivers|everglades/i, "grassrivers"],
  [/kalaga/i, "mount-kalaga"],
];

let localitySlugCache: Set<string> | null = null;

function localityPageSlugs(): Set<string> {
  localitySlugCache ??= new Set(
    getLocalityPages().map((group) => localitySlug(group.region)),
  );
  return localitySlugCache;
}

/**
 * Where a pin without its own page sends a visitor — and Google. The map holds
 * ~1,500 pins but only the hubs and editorial POIs carry unique copy, so the
 * rest 308 onto the page that actually covers them instead of serving 1,500
 * noindex shells that burn crawl budget.
 */
export function locationRedirectTarget(
  location: LocationIndexingFields & { category?: string; region?: string },
): string | undefined {
  if (hasOwnLocationPage(location)) return undefined;

  const collectiblePrefix = Object.keys(COLLECTIBLE_PREFIX_TYPE).find((prefix) =>
    location.slug.startsWith(prefix),
  );
  if (collectiblePrefix) {
    return `/collectibles/${COLLECTIBLE_PREFIX_TYPE[collectiblePrefix]}`;
  }

  const region = location.region?.trim();
  if (region) {
    const locality = localitySlug(region);
    if (localityPageSlugs().has(locality)) {
      return `/gta-6-real-life-locations/${locality}`;
    }

    const hub = REGION_HUB_PATTERNS.find(([pattern]) => pattern.test(region));
    if (hub) return `/locations/${hub[1]}`;
  }

  return "/gta-6-real-life-locations";
}

#!/usr/bin/env node
/** Update .env.local with GTADB GTA V tile configuration */

import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env.local");
const manifestPath = join(root, "public/tiles/gtadb-gta5-manifest.json");

const tileSet = process.argv[2] ?? "satellite";

let manifest = {
  imageUrl: "/tiles/los-santos-stitched.jpg",
  bounds: { minX: -4224, maxX: 4992, minY: -5120, maxY: 8448 },
  maxZoom: 6,
};

if (existsSync(manifestPath)) {
  manifest = { ...manifest, ...JSON.parse(readFileSync(manifestPath, "utf8")) };
}

const updates = {
  NEXT_PUBLIC_GTA5_GTADB_ENABLED: "true",
  NEXT_PUBLIC_GTA5_GTADB_TILE_SET: tileSet,
  NEXT_PUBLIC_GTA5_GTADB_MAP_IMAGE: manifest.imageUrl ?? "/tiles/los-santos-stitched.jpg",
  NEXT_PUBLIC_GTA5_MAP_MIN_X: String(manifest.bounds.minX),
  NEXT_PUBLIC_GTA5_MAP_MAX_X: String(manifest.bounds.maxX),
  NEXT_PUBLIC_GTA5_MAP_MIN_Y: String(manifest.bounds.minY),
  NEXT_PUBLIC_GTA5_MAP_MAX_Y: String(manifest.bounds.maxY),
  NEXT_PUBLIC_GTA5_MAP_CENTER_X: "-75",
  NEXT_PUBLIC_GTA5_MAP_CENTER_Y: "-818",
  NEXT_PUBLIC_GTA5_MAP_MAX_ZOOM: String(manifest.maxZoom ?? 6),
};

let lines = [];
if (existsSync(envPath)) {
  lines = readFileSync(envPath, "utf8").split("\n");
}

const keys = new Set(Object.keys(updates));
const filtered = lines.filter((line) => {
  const key = line.split("=")[0]?.trim();
  return !keys.has(key) && line.trim() !== "";
});

const block = [
  "",
  "# GTADB GTA V map tiles (auto-generated by npm run tiles:fetch-gtadb-gta5)",
  ...Object.entries(updates).map(([k, v]) => `${k}=${v}`),
  "",
];

writeFileSync(envPath, [...filtered, ...block].join("\n"));
console.log(`   Updated ${envPath}`);

#!/usr/bin/env node
/** Update .env.local with GTADB tile configuration */

import { readFileSync, writeFileSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const envPath = join(root, ".env.local");
const manifestPath = join(root, "public/tiles/gtadb-manifest.json");

const tileSet = process.argv[2] ?? "yanis,13";

let manifest = {
  imageUrl: "/tiles/leonida-stitched.jpg",
  bounds: { minX: -16384, maxX: 3584, minY: -8064, maxY: 12032 },
  center: { x: -6400, y: 1984 },
  maxZoom: 6,
};

if (existsSync(manifestPath)) {
  manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
}

const updates = {
  NEXT_PUBLIC_GTADB_ENABLED: "true",
  NEXT_PUBLIC_GTADB_TILE_SET: tileSet,
  NEXT_PUBLIC_GTADB_MAP_IMAGE: manifest.imageUrl,
  NEXT_PUBLIC_MAP_MIN_X: String(manifest.bounds.minX),
  NEXT_PUBLIC_MAP_MAX_X: String(manifest.bounds.maxX),
  NEXT_PUBLIC_MAP_MIN_Y: String(manifest.bounds.minY),
  NEXT_PUBLIC_MAP_MAX_Y: String(manifest.bounds.maxY),
  NEXT_PUBLIC_MAP_CENTER_X: String(manifest.center.x),
  NEXT_PUBLIC_MAP_CENTER_Y: String(manifest.center.y),
  NEXT_PUBLIC_MAP_MAX_ZOOM: String(manifest.maxZoom),
};

let lines = [];
if (existsSync(envPath)) {
  lines = readFileSync(envPath, "utf8").split("\n");
}

const keys = new Set(Object.keys(updates));
const filtered = lines.filter((line) => {
  const key = line.split("=")[0]?.trim();
  return !keys.has(key) && line.trim() !== "";
});

const block = [
  "",
  "# GTADB map tiles (auto-generated by npm run tiles:fetch-gtadb)",
  ...Object.entries(updates).map(([k, v]) => `${k}=${v}`),
  "",
];

writeFileSync(envPath, [...filtered, ...block].join("\n"));
console.log(`   Updated ${envPath}`);
